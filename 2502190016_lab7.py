# Define the nominal diameter and tolerance for the shaft for the 'verdict' and 'deviation' calculations
NOMINAL_DIA = 10.0 # Example nominal diameter
TOLERANCE = 0.5    # Example tolerance (e.g., +/- 0.5 from nominal)

class Shaft:
    def __init__(self, code, diameter):
        self.code = code
        self.diameter = diameter

    def deviation(self):
        """Calculates the absolute deviation from the nominal diameter."""
        return self.diameter - NOMINAL_DIA

    def verdict(self):
        """Determines the verdict based on the diameter and tolerance."""
        dev = self.deviation()
        if abs(dev) <= TOLERANCE:
            return "ACCEPT"
        elif dev > TOLERANCE:
            return "OVERSIZE"
        else: # dev < -TOLERANCE
            return "UNDERSIZE"


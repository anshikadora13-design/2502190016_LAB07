class Batch:
    def __init__(self, batch_no):
        self.batch_no = batch_no
        self.parts = [] # an empty rack, filled later

    def add(self, part):
        self.parts.append(part)

    def acceptance_pct(self):
        """Calculates the percentage of ACCEPTED parts in the batch."""
        if not self.parts:
            return 0.0
        accepted_count = sum(1 for part in self.parts if part.verdict() == "ACCEPT")
        return (accepted_count / len(self.parts)) * 100

    def worst(self):
        """Returns the part object with the largest absolute deviation."""
        if not self.parts:
            return None
        # Sort parts by absolute deviation in descending order and return the first one
        return max(self.parts, key=lambda p: abs(p.deviation()))


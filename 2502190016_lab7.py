import math

class Triangle:
    def __init__(self, side1, side2, side3):
        # Basic validation: sides must be positive
        if not (side1 > 0 and side2 > 0 and side3 > 0):
            raise ValueError("All sides of the triangle must be positive.")
        # Triangle inequality theorem: the sum of the lengths of any two sides of a triangle must be greater than the length of the third side.
        if not (side1 + side2 > side3 and side1 + side3 > side2 and side2 + side3 > side1):
            raise ValueError("The given side lengths do not form a valid triangle.")

        self.side1 = side1
        self.side2 = side2
        self.side3 = side3

    def calculate_perimeter(self):
        """Calculates the perimeter of the triangle."""
        return self.side1 + self.side2 + self.side3

    def calculate_area(self):
        """Calculates the area of the triangle using Heron's formula."""
        s = self.calculate_perimeter() / 2  # Semi-perimeter
        area = math.sqrt(s * (s - self.side1) * (s - self.side2) * (s - self.side3))
        return area

    def is_equilateral(self):
        """Checks if the triangle is equilateral (all sides equal)."""
        return self.side1 == self.side2 == self.side3

